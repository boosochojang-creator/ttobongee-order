// 소셜 닉네임에 전화번호가 섞여 DB에 남는 것을 차단.
// 원칙: 전화번호는 우리 시스템 어디에도 저장하지 않는다(유출 시 피해 최소화). 카카오 일부 사용자가
// 닉네임을 "이름+전화번호"로 설정해둔 사례 확인됨(예: '72년곽윤호01040389848').
// 저장 직전에 이 필터를 거친다 — 콜백/신규가입(social-new)/연결(link) 모두 적용.
export function sanitizeNickname(raw: string | null | undefined): string {
  let s = (raw || '').trim()
  if (!s) return ''
  // 1) 휴대폰 형태(하이픈/공백/점 유무 무관): 010-1234-5678 / 010 1234 5678 / 01012345678
  s = s.replace(/01[0-9][-.\s]?\d{3,4}[-.\s]?\d{4}/g, '')
  // 2) 남은 10~11자리 연속 숫자런(구분자 없는 전화번호 등)
  s = s.replace(/\d{10,11}/g, '')
  // 잔여 구분자/공백 정리
  s = s.replace(/^[\s\-.,·|/]+|[\s\-.,·|/]+$/g, '').replace(/\s{2,}/g, ' ').trim()
  return s // 남는 게 없으면 '' → 호출부에서 `|| null` 처리(전화만이던 닉네임은 저장 안 함)
}
